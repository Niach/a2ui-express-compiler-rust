#!/usr/bin/env python3
"""Regenerates crates/a2ui-express/src/syntax/uax31_tables.rs.

A v1.0 identifier (component id, catalog name, extension key) is
`[\\p{XID_Start}_][\\p{XID_Continue}]*` of a current Unicode version, the one
eui pins, while the Express lexer keeps the older sets compiled into
upstream's ANTLR lexer (syntax/xid.rs). This writes what the Unicode version
adds to the lexer's sets, and fails if the lexer has a code point Unicode
does not: the v1.0 sets must contain the lexer's.

Usage:
    curl -O https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt
    scripts/gen-uax31-tables.py DerivedCoreProperties.txt \\
        > crates/a2ui-express/src/syntax/uax31_tables.rs

Run scripts/gen-xid-tables.py first when the upstream pin moves. Use the
Unicode version of eui's generated xid.rs (vendor/eui/UPSTREAM pins eui).
"""

import os
import re
import sys

XID_RS = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "../crates/a2ui-express/src/syntax/xid.rs",
)


def unicode_set(lines: list[str], prop: str) -> set[int]:
    out: set[int] = set()
    for line in lines:
        m = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)\s", line)
        if m and m.group(3) == prop:
            out.update(range(int(m.group(1), 16), int(m.group(2) or m.group(1), 16) + 1))
    return out


def lexer_set(text: str, name: str) -> set[int]:
    body = text[text.index(f"static {name}:") :]
    body = body[: body.index("];")]
    out: set[int] = set()
    for lo, hi in re.findall(r"\(0x([0-9A-F]+), 0x([0-9A-F]+)\)", body):
        out.update(range(int(lo, 16), int(hi, 16) + 1))
    return out


def ranges(points: set[int]) -> list[tuple[int, int]]:
    out: list[list[int]] = []
    for c in sorted(points):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return [(lo, hi) for lo, hi in out]


def main() -> None:
    with open(sys.argv[1], encoding="utf-8") as f:
        lines = f.read().splitlines()
    version = re.match(r"# DerivedCoreProperties-([0-9.]+)\.txt", lines[0])
    if not version:
        sys.exit("not a DerivedCoreProperties.txt: no version in its first line")
    with open(XID_RS, encoding="utf-8") as f:
        xid_rs = f.read()

    print("// @generated by scripts/gen-uax31-tables.py from DerivedCoreProperties.txt")
    print("// and syntax/xid.rs. Do not edit by hand.")
    print()
    print("/// The Unicode version of the v1.0 identifier sets.")
    print(f'pub const UNICODE_VERSION: &str = "{version.group(1)}";')
    for name, lexer_name, prop, extra in (
        ("START_ADDED", "ID_START", "XID_Start", {ord("_")}),
        ("CONTINUE_ADDED", "ID_CONTINUE", "XID_Continue", set()),
    ):
        lexer = lexer_set(xid_rs, lexer_name)
        current = unicode_set(lines, prop) | extra
        if lexer - current:
            gone = ", ".join(f"U+{c:04X}" for c in sorted(lexer - current)[:10])
            sys.exit(f"the lexer's {lexer_name} has code points outside {prop}: {gone}")
        print()
        print(f"/// `{prop}` of this Unicode version, less the lexer's `{lexer_name}`.")
        print(f"pub(crate) static {name}: &[(u32, u32)] = &[")
        for lo, hi in ranges(current - lexer):
            print(f"    (0x{lo:X}, 0x{hi:X}),")
        print("];")


if __name__ == "__main__":
    main()
