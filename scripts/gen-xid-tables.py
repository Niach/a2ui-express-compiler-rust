#!/usr/bin/env python3
"""Regenerates crates/a2ui-express/src/syntax/xid.rs.

The identifier character sets are taken from the upstream ANTLR lexer itself
(the serialized ATN of the generated Python lexer), not from a Unicode
library, so the Rust lexer accepts exactly the code points upstream does.

Usage:
    pip install 'antlr4-python3-runtime>=4.13,<4.14'
    scripts/gen-xid-tables.py <a2ui-checkout> > crates/a2ui-express/src/syntax/xid.rs

<a2ui-checkout> is a checkout of a2ui-project/a2ui at the commit pinned in
vendor/a2ui/UPSTREAM.
"""

import os
import sys

GEN = "python/a2ui_agent/src/a2ui/inference_formats/express/generated"


def main() -> None:
    sys.path.insert(0, os.path.join(sys.argv[1], GEN))
    from express_lexer import ExpressLexer  # type: ignore

    atn = ExpressLexer.atn
    rule = ExpressLexer.ruleNames.index("IDENTIFIER")
    seen, sets, queue = set(), [], [atn.ruleToStartState[rule]]
    while queue:
        state = queue.pop(0)
        if state.stateNumber in seen:
            continue
        seen.add(state.stateNumber)
        for t in state.transitions:
            if t.label is not None and len(t.label) > 0:
                sets.append([(r.start, r.stop - 1) for r in t.label.intervals])
            if t.target.ruleIndex == rule:
                queue.append(t.target)
    start, cont = sets
    print("// @generated by scripts/gen-xid-tables.py from the upstream ANTLR lexer.")
    print("// Do not edit by hand.")
    print()
    for name, ranges, doc in (
        ("ID_START", start, "`[\\p{XID_Start}_]` as compiled into upstream's lexer."),
        ("ID_CONTINUE", cont, "`[\\p{XID_Continue}]` as compiled into upstream's lexer."),
    ):
        print(f"/// {doc}")
        print(f"pub(crate) static {name}: &[(u32, u32)] = &[")
        for lo, hi in ranges:
            print(f"    (0x{lo:X}, 0x{hi:X}),")
        print("];")
        print()


if __name__ == "__main__":
    main()
