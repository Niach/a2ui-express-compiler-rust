#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hex_round_trips() {
        for s in ["#eef800", "#0e0e0e", "#ffffff1a"] {
            assert_eq!(Rgba::parse(s).unwrap().hex(), s);
        }
        assert_eq!(Rgba::parse("#EEF800").unwrap().hex(), "#eef800");
        assert!(Rgba::parse("#fff").is_none());
    }

    #[test]
    fn oklab_round_trips_every_grey() {
        for v in 0..=255u8 {
            let c = Rgba::rgb(v, v, v);
            let (l, a, b) = c.oklab();
            assert_eq!(Rgba::from_oklab(l, a, b, 255), c);
        }
        let (l, _, _) = Rgba::WHITE.oklab();
        assert!((l - 1.0).abs() < 1e-6);
    }

    #[test]
    fn contrast_matches_wcag() {
        assert!((contrast(Rgba::WHITE, Rgba::BLACK) - 21.0).abs() < 1e-9);
        let c = contrast(Rgba::parse("#767676").unwrap(), Rgba::WHITE);
        assert!((c - 4.54).abs() < 0.01, "{c}");
    }
}
