//! Colour arithmetic for the theme expander, deterministic on every target.
//!
//! The expander's output is pinned as golden JSON and replayed by the wasm
//! and Python builds, so a colour may not depend on a platform's `powf` or
//! `cbrt`. Everything here uses only `+ - * /` and `sqrt` (IEEE-exact):
//! the sRGB transfer function is a table of the 256 byte values, its inverse
//! a search in that table, and the OKLab cube root a fixed number of Newton
//! steps.

/// An sRGB colour with alpha, 8 bits a channel.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Rgba {
    pub r: u8,
    pub g: u8,
    pub b: u8,
    pub a: u8,
}

impl Rgba {
    pub const WHITE: Rgba = Rgba::rgb(255, 255, 255);
    pub const BLACK: Rgba = Rgba::rgb(0, 0, 0);

    pub const fn rgb(r: u8, g: u8, b: u8) -> Rgba {
        Rgba { r, g, b, a: 255 }
    }

    /// `#rrggbb` or `#rrggbbaa`, either case.
    pub fn parse(s: &str) -> Option<Rgba> {
        let h = s.strip_prefix('#')?;
        if !matches!(h.len(), 6 | 8) || !h.bytes().all(|b| b.is_ascii_hexdigit()) {
            return None;
        }
        let byte = |i: usize| u8::from_str_radix(&h[i..i + 2], 16).ok();
        Some(Rgba {
            r: byte(0)?,
            g: byte(2)?,
            b: byte(4)?,
            a: if h.len() == 8 { byte(6)? } else { 255 },
        })
    }

    /// Lowercase `#rrggbb`, or `#rrggbbaa` when not opaque.
    pub fn hex(self) -> String {
        if self.a == 255 {
            format!("#{:02x}{:02x}{:02x}", self.r, self.g, self.b)
        } else {
            format!("#{:02x}{:02x}{:02x}{:02x}", self.r, self.g, self.b, self.a)
        }
    }

    /// This colour composited over an opaque `under`.
    pub fn over(self, under: Rgba) -> Rgba {
        if self.a == 255 {
            return self;
        }
        let a = self.a as f64 / 255.0;
        let ch = |top: u8, bottom: u8| round_byte(top as f64 * a + bottom as f64 * (1.0 - a));
        Rgba::rgb(ch(self.r, under.r), ch(self.g, under.g), ch(self.b, under.b))
    }

    /// WCAG relative luminance (alpha ignored).
    pub fn luminance(self) -> f64 {
        0.2126 * LIN[self.r as usize] + 0.7152 * LIN[self.g as usize] + 0.0722 * LIN[self.b as usize]
    }

    /// OKLab `(L, a, b)`.
    pub fn oklab(self) -> (f64, f64, f64) {
        let (r, g, b) = (LIN[self.r as usize], LIN[self.g as usize], LIN[self.b as usize]);
        let l = cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
        let m = cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
        let s = cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
        (
            0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
            1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
            0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s,
        )
    }

    /// The colour at OKLab `(L, a, b)`, each channel clamped into sRGB.
    pub fn from_oklab(l: f64, a: f64, b: f64, alpha: u8) -> Rgba {
        let l_ = l + 0.3963377774 * a + 0.2158037573 * b;
        let m_ = l - 0.1055613458 * a - 0.0638541728 * b;
        let s_ = l - 0.0894841775 * a - 1.2914855480 * b;
        let (l3, m3, s3) = (l_ * l_ * l_, m_ * m_ * m_, s_ * s_ * s_);
        let r = 4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3;
        let g = -1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3;
        let bl = -0.0041960863 * l3 - 0.7034186147 * m3 + 1.7076147010 * s3;
        Rgba {
            r: from_linear(r),
            g: from_linear(g),
            b: from_linear(bl),
            a: alpha,
        }
    }

    /// OKLab lightness.
    pub fn lightness(self) -> f64 {
        self.oklab().0
    }

    /// The same hue and chroma at OKLab lightness `l` (chroma scaled by
    /// `chroma`).
    pub fn with_lightness(self, l: f64, chroma: f64) -> Rgba {
        let (_, a, b) = self.oklab();
        Rgba::from_oklab(l.clamp(0.0, 1.0), a * chroma, b * chroma, self.a)
    }

    /// The sRGB mix `(1 - t) * self + t * other`, opaque.
    pub fn mix(self, other: Rgba, t: f64) -> Rgba {
        let ch = |x: u8, y: u8| round_byte(x as f64 * (1.0 - t) + y as f64 * t);
        Rgba::rgb(ch(self.r, other.r), ch(self.g, other.g), ch(self.b, other.b))
    }

    pub fn opaque(self) -> Rgba {
        Rgba { a: 255, ..self }
    }
}

/// The WCAG contrast ratio of two colours, each composited over `base` first.
pub fn contrast(x: Rgba, y: Rgba) -> f64 {
    let (a, b) = (x.luminance(), y.luminance());
    let (hi, lo) = if a > b { (a, b) } else { (b, a) };
    (hi + 0.05) / (lo + 0.05)
}

fn round_byte(v: f64) -> u8 {
    let v = v.clamp(0.0, 255.0);
    let f = v.floor();
    (if v - f >= 0.5 { f + 1.0 } else { f }) as u8
}

/// The byte whose linear value is nearest `v` (ties to the lower).
fn from_linear(v: f64) -> u8 {
    if v <= 0.0 {
        return 0;
    }
    if v >= 1.0 {
        return 255;
    }
    let (mut lo, mut hi) = (0usize, 255usize);
    while hi - lo > 1 {
        let mid = (lo + hi) / 2;
        if LIN[mid] <= v {
            lo = mid;
        } else {
            hi = mid;
        }
    }
    if v - LIN[lo] <= LIN[hi] - v { lo as u8 } else { hi as u8 }
}

/// The real cube root by Newton's method from a fixed start: arithmetic
/// only, so every target computes the same bits.
fn cbrt(x: f64) -> f64 {
    if x <= 0.0 {
        return 0.0;
    }
    let mut y = if x > 1.0 { x } else { 1.0 };
    for _ in 0..80 {
        y = (2.0 * y + x / (y * y)) / 3.0;
    }
    y
}

